"""Streamlit page -- Evaluation results browser.

Renders tables, figures, and markdown reports from ``reports/``.
"""

from __future__ import annotations

import pathlib

import streamlit as st

# ---------------------------------------------------------------------------
# Page config
# ---------------------------------------------------------------------------

st.set_page_config(
    page_title="Results -- Redact, Then Ask",
    page_icon="📊",
    layout="wide",
    initial_sidebar_state="expanded",
)

# ---------------------------------------------------------------------------
# Inject custom CSS
# ---------------------------------------------------------------------------

try:
    css_path = pathlib.Path(__file__).resolve().parent.parent / "style.css"
    if css_path.exists():
        css = css_path.read_text(encoding="utf-8")
        st.markdown(f"<style>{css}</style>", unsafe_allow_html=True)
except Exception:
    pass

# ---------------------------------------------------------------------------
# Header
# ---------------------------------------------------------------------------

st.title("Results")
st.caption("Evaluation tables and figures generated by the experiment harness")

# ---------------------------------------------------------------------------
# Locate reports directory
# ---------------------------------------------------------------------------

REPORTS_DIR = pathlib.Path(__file__).resolve().parent.parent.parent / "reports"
TABLES_DIR = REPORTS_DIR / "tables"
FIGURES_DIR = REPORTS_DIR / "figures"
RESULTS_MD = REPORTS_DIR / "RESULTS.md"


def _has_any_reports() -> bool:
    """Return True if there is at least one result artefact."""
    for d in (TABLES_DIR, FIGURES_DIR):
        if d.exists() and any(d.iterdir()):
            return True
    return bool(RESULTS_MD.exists() and RESULTS_MD.stat().st_size > 100)


if not _has_any_reports():
    st.info(
        "No evaluation reports found yet. Run `make eval` or `make experiments` "
        "to generate results.",
        icon="🧪",
    )
    st.stop()

# ---------------------------------------------------------------------------
# RESULTS.md overview
# ---------------------------------------------------------------------------

if RESULTS_MD.exists():
    content = RESULTS_MD.read_text(encoding="utf-8").strip()
    if content:
        with st.expander("RESULTS.md (overview)", expanded=True):
            st.markdown(content, unsafe_allow_html=True)

# ---------------------------------------------------------------------------
# Helpers
# ---------------------------------------------------------------------------

# Experiment grouping order
GROUPS = [
    ("Detection", "detection"),
    ("E1 -- Privacy vs. Utility", "e1"),
    ("E2 -- Leak Test", "e2"),
    ("E3 -- Error Propagation", "e3"),
    ("E4 -- Additional", "e4"),
    ("Classifier", "classifier"),
]


def _group_for_file(name: str) -> str:
    """Return the group key for a filename, falling back to 'other'."""
    lower = name.lower()
    for _, key in GROUPS:
        if key in lower:
            return key
    return "other"


def _render_table_md(path: pathlib.Path) -> None:
    text = path.read_text(encoding="utf-8").strip()
    if text:
        st.markdown(text, unsafe_allow_html=True)


def _render_table_csv(path: pathlib.Path) -> None:
    import pandas as pd

    try:
        df = pd.read_csv(path)
        st.dataframe(df, use_container_width=True)
    except Exception as exc:
        st.error(f"Could not load {path.name}: {exc}")


def _render_figure(path: pathlib.Path) -> None:
    st.image(str(path), caption=path.stem.replace("_", " ").title())


# ---------------------------------------------------------------------------
# Gather artefacts
# ---------------------------------------------------------------------------

tables_md: list[pathlib.Path] = sorted(TABLES_DIR.glob("*.md")) if TABLES_DIR.exists() else []
tables_csv: list[pathlib.Path] = sorted(TABLES_DIR.glob("*.csv")) if TABLES_DIR.exists() else []
figures: list[pathlib.Path] = sorted(FIGURES_DIR.glob("*.png")) if FIGURES_DIR.exists() else []

all_files: list[pathlib.Path] = tables_md + tables_csv + figures

# ---------------------------------------------------------------------------
# Render grouped
# ---------------------------------------------------------------------------

rendered_groups: set[str] = set()

for group_label, group_key in GROUPS:
    group_files = [f for f in all_files if _group_for_file(f.name) == group_key]
    if not group_files:
        continue

    rendered_groups.add(group_key)
    st.markdown("---")
    st.subheader(group_label)

    for f in group_files:
        st.markdown(
            f'<div class="rta-card"><strong>{f.name}</strong></div>',
            unsafe_allow_html=True,
        )
        if f.suffix == ".md":
            _render_table_md(f)
        elif f.suffix == ".csv":
            _render_table_csv(f)
        elif f.suffix == ".png":
            _render_figure(f)

# Ungrouped files
ungrouped = [f for f in all_files if _group_for_file(f.name) == "other"]
if ungrouped:
    st.markdown("---")
    st.subheader("Other")
    for f in ungrouped:
        st.markdown(
            f'<div class="rta-card"><strong>{f.name}</strong></div>',
            unsafe_allow_html=True,
        )
        if f.suffix == ".md":
            _render_table_md(f)
        elif f.suffix == ".csv":
            _render_table_csv(f)
        elif f.suffix == ".png":
            _render_figure(f)
